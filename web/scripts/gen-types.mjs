// Generates TypeScript types from the JSON Schemas in ../contracts (the engine's contracts).
// Output is committed in src/types/generated/; rerun after a contract change: npm run gen:types
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "..", "..", "contracts");
const out = join(here, "..", "src", "types", "generated");
const banner = "/* Generated by scripts/gen-types.mjs from contracts/*.schema.json. Do not edit by hand. */";

mkdirSync(out, { recursive: true });
for (const [schema, file] of [
  ["claim.schema.json", "claim.ts"],
  ["insight.schema.json", "insight.ts"],
  ["match.schema.json", "match.ts"],
  ["fixtures.schema.json", "fixtures.ts"],
]) {
  const ts = await compileFromFile(join(contracts, schema), {
    bannerComment: banner,
    additionalProperties: false,
    strictIndexSignatures: true,
    style: { printWidth: 120 },
  });
  writeFileSync(join(out, file), ts);
  console.log(`wrote src/types/generated/${file}`);
}
