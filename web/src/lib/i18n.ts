  (family ?? "pattern").replace(/^pat_/, "").replace(/_/g, " ");

export const LANG_NAMES: Record<Lang, string> = { en: "English", es: "Español", fr: "Français" };

export const tr = (k: Key, lang: Lang) => STRINGS[lang][k];
export const typeLabel = (type: InsightType, lang: Lang) =>
  TYPES[lang][type] ?? TYPES.en[type] ?? type.replace(/_/g, " ");

export function useT() {
  const lang = useSettings((s) => s.lang);
  return { lang, t: (k: Key) => tr(k, lang), typeLabel: (x: InsightType) => typeLabel(x, lang) };
}
