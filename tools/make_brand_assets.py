"""Brand derivatives for the web app, made from the local originals in design/source/.

    python -m tools.make_brand_assets            # everything
    python -m tools.make_brand_assets logos      # one step: logos | icons | teams | hero

Outputs (all committed; the originals are not):
  web/public/brand/optix-mark.svg, optix-logo.svg              currentColor, for dark and light
  web/public/brand/optix-mark-accent.svg, optix-logo-accent.svg  the app accent (--accent)
  web/src/components/brand/logoPaths.ts                         the same paths, for the inline header logo
  web/public/favicon.ico, icons/*.png, manifest.webmanifest     favicon set from the mark
  web/public/brand/teams/badge-<code>-<48|96|192>.webp           crests on transparent background
  web/public/brand/teams/mini-<code>.svg                         small-size mini-mark (disc + code)
  web/public/brand/teams/kit-<code>-<home|away>.webp             shirts on transparent background
  web/public/brand/hero-lineup-<1600|800>.webp                   the audited, cleaned hero

Every raster is written without metadata (no EXIF, ICC, text chunks): images are rebuilt from pixel
data before saving. The hero is made only from design/source/hero-lineup-clean.png (see
docs/brand-audit.md); players-trio is BLOCKED and never read here.
"""
from __future__ import annotations

import io
import json
import re
import sys
from pathlib import Path

import numpy as np
import vtracer
from PIL import Image, ImageDraw, ImageOps

SRC = Path("design/source")
PUB = Path("web/public")
BRAND = PUB / "brand"
TEAMS = BRAND / "teams"
ACCENT = "#37e6a8"  # --accent in web/src/styles/tokens.css
BG = "#05080f"  # --bg
CODES = ["aur", "ntg", "cal", "ves", "har"]
NAMES = {"aur": "Aurelia Rovers", "ntg": "Northgate Town", "cal": "Calder Athletic",
         "ves": "Veston United", "har": "Harbor Wanderers"}


def clean_copy(im: Image.Image) -> Image.Image:
    """A fresh image from the pixel data only, so nothing (EXIF, ICC, text) is carried over."""
    return Image.frombytes(im.mode, im.size, im.tobytes())


def save(im: Image.Image, path: Path, **kw):
    path.parent.mkdir(parents=True, exist_ok=True)
    clean_copy(im).save(path, **kw)


# ---------------------------------------------------------------- logos

def _bitmap(name: str, pad: int = 8) -> Image.Image:
    g = Image.open(SRC / f"{name}.png").convert("L").point(lambda v: 0 if v < 128 else 255)
    x0, y0, x1, y1 = ImageOps.invert(g).getbbox()
    return g.crop((x0 - pad, y0 - pad, x1 + pad, y1 + pad))


def _trace(bw: Image.Image) -> tuple[str, list[str]]:
    b = io.BytesIO()
    bw.convert("RGB").save(b, "PNG")
    svg = vtracer.convert_raw_image_to_svg(b.getvalue(), img_format="png", colormode="binary",
                                           filter_speckle=8, corner_threshold=60, length_threshold=4.0,
                                           splice_threshold=45, path_precision=1, mode="spline")
    w, h = re.search(r'width="(\d+)" height="(\d+)"', svg).groups()
    paths = []
    for d, tx, ty in re.findall(r'<path d="([^"]+)" fill="#000000" transform="translate\(([-\d.]+),([-\d.]+)\)"/>', svg):
        paths.append(f'<path d="{d.strip()}" transform="translate({float(tx):.1f} {float(ty):.1f})"/>')
    return f"0 0 {w} {h}", paths


def _svg(viewbox: str, paths: list[str], label: str, fill: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" role="img" aria-label="{label}">'
            f'<title>{label}</title><g fill="{fill}">' + "".join(paths) + "</g></svg>\n")


def logos():
    ts = ["// Generated by tools/make_brand_assets.py from the traced logos (do not edit by hand).",
          "export type LogoPaths = { viewBox: string; paths: { d: string; t: string }[] };"]
    for name, stem, key in (("logo-mark", "optix-mark", "MARK"), ("logo-wordmark", "optix-logo", "WORDMARK")):
        vb, paths = _trace(_bitmap(name))
        (BRAND / f"{stem}.svg").parent.mkdir(parents=True, exist_ok=True)
        (BRAND / f"{stem}.svg").write_text(_svg(vb, paths, "Optix", "currentColor"))
        (BRAND / f"{stem}-accent.svg").write_text(_svg(vb, paths, "Optix", ACCENT))
        items = ", ".join(json.dumps({"d": re.search(r'd="([^"]+)"', p).group(1),
                                      "t": re.search(r"translate\(([^)]+)\)", p).group(1)}) for p in paths)
        ts.append(f"export const {key}: LogoPaths = {{ viewBox: {json.dumps(vb)}, paths: [{items}] }};")
        print(f"{stem}: {len(paths)} paths, viewBox {vb}")
    # The same paths inline, so the header logo takes currentColor from the page.
    p = Path("web/src/components/brand/logoPaths.ts")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(ts) + "\n")


# ---------------------------------------------------------------- icons

def _mark_small() -> Image.Image:
    """The mark without the arrow, strokes thickened: for 16-48 px, where the thin arrow vanishes."""
    import cv2
    bw = np.array(_bitmap("logo-mark", pad=0))
    ink = (bw < 128).astype(np.uint8)
    n, lab, stats, _ = cv2.connectedComponentsWithStats(ink, 8)
    arrow = 1 + int(np.argmin(stats[1:, cv2.CC_STAT_TOP]))  # the topmost shape is the arrow
    ink[lab == arrow] = 0
    ink = cv2.dilate(ink, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (31, 31)))
    ys, xs = np.nonzero(ink)
    ink = ink[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    return Image.fromarray((ink * 255).astype(np.uint8))


def _mark_full() -> Image.Image:
    bw = _bitmap("logo-mark", pad=0)
    return ImageOps.invert(bw)


def _icon(alpha: Image.Image, size: int, inset: float, radius: float) -> Image.Image:
    """Accent mark on a dark rounded square, drawn at 8x and downsampled."""
    S = size * 8
    tile = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(tile).rounded_rectangle((0, 0, S - 1, S - 1), radius=int(S * radius), fill=BG)
    w = int(S * (1 - 2 * inset))
    a = alpha.copy()
    a.thumbnail((w, w), Image.LANCZOS)
    col = Image.new("RGBA", a.size, ACCENT)
    col.putalpha(a)
    tile.alpha_composite(col, ((S - a.width) // 2, (S - a.height) // 2))
    return tile.resize((size, size), Image.LANCZOS)


def icons():
    small, full = _mark_small(), _mark_full()
    d = PUB / "icons"
    sizes = {16: small, 32: small, 48: small, 180: full, 192: full, 512: full}
    made = {}
    for s, src in sizes.items():
        im = _icon(src, s, inset=0.04 if s <= 48 else 0.12, radius=0.22)
        made[s] = im
        name = "apple-touch-icon.png" if s == 180 else f"icon-{s}.png"
        save(im, d / name, optimize=True)
    # Apple touch icons are shown without transparency: give it a solid background.
    flat = Image.new("RGB", (180, 180), BG)
    flat.paste(made[180], (0, 0), made[180])
    save(flat, d / "apple-touch-icon.png", optimize=True)
    save(made[48], PUB / "favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)],
         append_images=[made[16], made[32]])
    manifest = {"name": "Optix: verified match insights", "short_name": "Optix", "start_url": "./",
                "display": "standalone", "background_color": BG, "theme_color": BG,
                "icons": [{"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
                          {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png"}]}
    (PUB / "manifest.webmanifest").write_text(json.dumps(manifest, indent=2) + "\n")
    print("icons: favicon.ico (16/32/48 small mark), 16/32/48/180/192/512 png, manifest")


STEPS = {"logos": logos, "icons": icons}


def main(argv):
    for step in (argv or list(STEPS)):
        STEPS[step]()


if __name__ == "__main__":
    main(sys.argv[1:])
