"""Realism report: every calibration target measured on the small and the full league, plus xG
calibration by bin, goal dispersion, goal timing and league correlations. No network access: the
leagues are generated in memory from a seed.

    python -m tools.realism_report                  # writes docs/realism-report.md
    python -m tools.realism_report --seed 7 --out /tmp/report.md

If docs/realism-v1-measured.json exists (the v1 generator measured with today's definitions), a
"v1" column is added so the report shows before and after.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from data_gen import calibration
from data_gen.generate import (EXTRA_PLAYER_TRAITS, fixtures_for, make_players, play_season, season_tables,
                               small_season)
from data_gen.league import full_teams

ROOT = Path(__file__).resolve().parent.parent
V1 = ROOT / "docs" / "realism-v1-measured.json"
XG_BINS = ((0.0, 0.05), (0.05, 0.10), (0.10, 0.20), (0.20, 0.40), (0.40, 1.01))


def small_league(seed: int) -> dict:
    return season_tables(*small_season(seed, make_players(seed)))


def full_league(seed: int) -> tuple[dict, list]:
    teams = full_teams()
    by_id = {t.team_id: t for t in teams}
    players = make_players(seed, EXTRA_PLAYER_TRAITS, teams)
    fixtures = fixtures_for([t.team_id for t in teams], seed)
    return season_tables(play_season(seed, fixtures, players, by_id, seed_mult=10_000), fixtures), teams


def xg_bins(shots: list) -> list:
    rows = []
    for lo, hi in XG_BINS:
        s = [x for x in shots if lo <= float(x["xg"]) < hi]
        xg = sum(float(x["xg"]) for x in s)
        goals = sum(1 for x in s if x["shot_result"] == "goal")
        sd = math.sqrt(sum(float(x["xg"]) * (1 - float(x["xg"])) for x in s))
        rows.append(dict(bin=f"{lo:.2f}-{min(hi, 1.0):.2f}", shots=len(s), xg=round(xg, 1), goals=goals,
                         z=round((goals - xg) / sd, 2) if sd else None))
    return rows


def goal_timing(events: list) -> dict:
    goals = [e for e in events if e["event_type"] == "shot" and e["outcome"] == "goal"]
    out = {}
    for label, period, lo, hi in (("1st half 0-15", "1", 0, 15), ("1st half 30-45+", "1", 30, 200),
                                  ("2nd half 45-60", "2", 45, 60), ("2nd half 75-90+", "2", 75, 200)):
        out[label] = sum(1 for e in goals if str(e["period"]) == period and lo <= int(e["minute"]) < hi)
    return out


def _fmt(v):
    if v is None:
        return "–"
    return f"{v:.3f}" if abs(v) < 10 else f"{v:.1f}"


def report(seed: int) -> str:
    small = calibration.check(calibration.season_stats(small_league(seed)))
    full_t, teams = full_league(seed)
    full_stats = calibration.season_stats(full_t)
    full = calibration.check(full_stats)
    v1 = json.loads(V1.read_text()) if V1.exists() else None

    lines = [f"# Realism report (seed {seed})", "",
             "Generated by `python -m tools.realism_report`. Ranges and sources: `data_gen/calibration.py`. "
             "A value passes inside [lo - a, hi + a], a = 2 sd / sqrt(n) (the sampling allowance). "
             "Season-shape targets apply to the 20-team league only.", ""]
    head = "| Target | Range | Source |" + (" v1 full |" if v1 else "") + " Small league | Full league |"
    lines += [head, "|" + "---|" * (head.count("|") - 1)]
    for k, t in calibration.TARGETS.items():
        s, f = small[k], full[k]
        cell_s = f"{_fmt(s['measured'])} {'ok' if s['passed'] else 'OUT'}" if s["applicable"] else "n/a"
        cell_f = f"{_fmt(f['measured'])} {'ok' if f['passed'] else 'OUT'}"
        before = ""
        if v1:
            b = v1.get(k)
            before = f" {_fmt(b)} |" if b is not None else " – |"
        lines.append(f"| {k} | {t['lo']}-{t['hi']} | {t['source']} |{before} {cell_s} | {cell_f} |")
    out_s = sorted(k for k, r in small.items() if r["applicable"] and not r["passed"])
    out_f = sorted(k for k, r in full.items() if r["applicable"] and not r["passed"])
    lines += ["", f"Outside range: small league {out_s or 'none'}; full league {out_f or 'none'}.", ""]

    lines += ["## xG calibration by bin (full league)", "",
              "| xG bin | Shots | xG | Goals | z |", "|---|---|---|---|---|"]
    lines += [f"| {r['bin']} | {r['shots']} | {r['xg']} | {r['goals']} | {r['z']} |" for r in xg_bins(full_t["shots"])]

    g = [int(m[k]) for m in full_t["matches"] for k in ("home_score", "away_score")]
    mean = sum(g) / len(g)
    var = sum((x - mean) ** 2 for x in g) / (len(g) - 1)
    lines += ["", "## Goals per team per match (full league)", "",
              f"Mean {mean:.2f}, variance {var:.2f}, variance / mean {var / mean:.2f} (Poisson is 1; "
              "real leagues run slightly over 1).", "",
              "## Goal timing (full league, goals by football minute)", "",
              "| Window | Goals |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in goal_timing(full_t["events"]).items()]

    press = {t.team_id: t.press for t in teams}
    ppda = full_stats["_ppda_by_team"]
    ts = sorted(ppda)
    lines += ["", "## League correlations (full league, 20 teams)", "",
              "| Pair | r | Expected sign |", "|---|---|---|",
              f"| possession vs shots | {full_stats['corr_possession_shots']:.2f} | + |",
              f"| possession vs pass accuracy | {full_stats['corr_possession_pass_accuracy']:.2f} | + |",
              f"| PPDA vs possession | {full_stats['corr_ppda_possession']:.2f} | - |",
              f"| press dial vs PPDA | {calibration.pearson([press[x] for x in ts], [ppda[x] for x in ts]):.2f} | - |",
              ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "realism-report.md")
    a = ap.parse_args(argv)
    a.out.write_text(report(a.seed))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
